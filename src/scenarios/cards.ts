export const CARD_BY_ID = Object.fromEntries(CARDS.map((c) => [c.id, c])) as Record<CardId, CardDef>

export function cardValues(card: CardId, overrides?: Values): Values {
  return { ...CARD_BY_ID[card].values, ...overrides }
}

// A one-line summary of an instance for setup rows: its distinguishing values.
const SUMMARY_KEYS: Partial<Record<CardId, string[]>> = {
  email: ["email"],
  phone: ["mobile"],
  passport: ["familyName", "documentNumber"],
  idcard: ["familyName", "documentNumber"],
  driving: ["familyName", "documentNumber", "categories"],
  personal: ["givenName", "familyName", "bsn"],
  address: ["street", "houseNumber", "city"],
  pid: ["familyName", "city", "country"],
  iban: ["holder", "iban"],
  diploma: ["education", "achieved"],
  exam: ["exam", "date"],
  study: ["name"],
  bsn: ["bsn"],
}

export function summarise(card: CardId, overrides?: Values): string {
  const v = cardValues(card, overrides)
  return (SUMMARY_KEYS[card] ?? Object.keys(v)).map((k) => v[k]).filter(Boolean).join(" · ")
}

// A card name mid-sentence: "No passport", but "No ID card", "an EU identity".
export function inSentence(name: string): string {
  return /^[A-Z]{2}/.test(name) ? name : name.charAt(0).toLowerCase() + name.slice(1)
}
