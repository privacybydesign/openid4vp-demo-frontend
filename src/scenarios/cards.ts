// The card catalogue: what each abstract card is in each source, and how its
// canonical values become that source's attributes or claims.
//
// irma-demo attribute sets were checked against the staging IRMA server, which
// refuses an issuance missing a required attribute. Two types were swapped for
// that reason: inz-id-card.idCard has revocation enabled and the server has no
// revocation server for it, and stemmen.stempas's votingnumber is randomblind
// (generated by the server, so it must be left out).

export const VERAMO_ISSUER_BASE =
  import.meta.env.VITE_VERAMO_ISSUER_API_URL || "https://veramo-issuer.openid4vc.staging.yivi.app"

export interface IrmaSource {
  credential: string
  // ShouldBeSingleton in the irma-demo scheme. An inner con of a condiscon may hold
  // at most one credential type that isn't.
  singleton?: true
  attributes: (v: Values) => Record<string, string>
  // irmago refuses to issue a revocation-enabled credential without a key.
  revocable?: boolean
}

export interface PbdfSource {
  credential: string
  // Where the tester gets it: the Yivi app's "Add data" list on the staging scheme.
  addHint: string
}

export interface VeramoSource {
  // Configuration ids are `${name}CredentialSdJwt` and `${name}CredentialVcdm`.
  name: string
  // SD-JWT VC vct: `${VERAMO_ISSUER_BASE}/vct/${vct}`.
  vct: string
  // Which formats the staging issuer has a configuration for today.
  available: Record<VeramoFormat, boolean>
  // Whether the SD-JWT VC configuration has a status list, so a credential can be
  // revoked. The VCDM configurations have none.
  revocable: boolean
  data: (v: Values) => object
}

export interface EudiSource {
  label: string
  format: "SD-JWT VC" | "mdoc"
  configurationId: string
  data: (v: Values) => object
}

export interface CardDef {
  id: CardId
  name: string
  values: Values
  note?: string
  irma?: IrmaSource
  pbdf?: PbdfSource
  veramo?: VeramoSource
  eudi?: EudiSource[]
}

// "1991-03-12" -> "12-03-1991", the date form the irma-demo schemes use.
export function irmaDate(iso: string): string {
  const [y, m, d] = iso.split("-")
  return d && m && y ? `${d}-${m}-${y}` : iso
}

function yes(v: string | undefined): string {
  return v === "no" ? "no" : "yes"
}

function categories(v: Values): string[] {
  return (v.categories ?? "").split(",").map((c) => c.trim()).filter(Boolean)
}

export function veramoConfigurationId(card: CardDef, format: VeramoFormat): string {
  return `${card.veramo!.name}Credential${format === "sd" ? "SdJwt" : "Vcdm"}`
}

export function veramoVct(card: CardDef): string {
  return `${VERAMO_ISSUER_BASE}/vct/${card.veramo!.vct}`
}

export function veramoVcdmType(card: CardDef): string[] {
  return ["VerifiableCredential", `${card.veramo!.name}VcdmCredential`]
}

